"""Render the guardrail Terraform. Agent Radius writes these files; it never
runs ``terraform apply`` (or plan) and never calls a mutating AWS API."""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from typing import Any

from agent_radius.catalog import CATALOG
from agent_radius.guardrails.hcl import hcl_string, render_value

BOUNDARY_TAMPER_ACTIONS = [
    "iam:DeleteRolePermissionsBoundary",
    "iam:PutRolePermissionsBoundary",
    "iam:DeleteUserPermissionsBoundary",
    "iam:PutUserPermissionsBoundary",
    "iam:CreatePolicyVersion",
    "iam:SetDefaultPolicyVersion",
    "iam:DeletePolicyVersion",
]


def deny_policy_document(actions: list[str]) -> dict[str, Any]:
    return {
        "Version": "2012-10-17",
        "Statement": [
            {
                "Sid": "AgentRadiusDenyDestructive",
                "Effect": "Deny",
                "Action": sorted(set(actions)),
                "Resource": "*",
            }
        ],
    }


def boundary_policy_document() -> dict[str, Any]:
    destructive = sorted({c.action for c in CATALOG})
    tamper = sorted(set(BOUNDARY_TAMPER_ACTIONS) - set(destructive))
    return {
        "Version": "2012-10-17",
        "Statement": [
            {
                "Sid": "CeilingIsWhateverTheIdentityPolicyGrants",
                "Effect": "Allow",
                "Action": "*",
                "Resource": "*",
            },
            {
                "Sid": "NeverIrreversibleActions",
                "Effect": "Deny",
                "Action": destructive,
                "Resource": "*",
            },
            {
                "Sid": "NeverTamperWithThisBoundary",
                "Effect": "Deny",
                "Action": tamper,
                "Resource": "*",
            },
        ],
    }


def _tf_name(raw: str) -> str:
    name = re.sub(r"[^A-Za-z0-9_]", "_", raw).strip("_").lower() or "x"
    if not re.match(r"^[a-z_]", name):
        name = "_" + name
    return name[:60]


@dataclass
class GuardrailBundle:
    files: dict[str, str] = field(default_factory=dict)  # filename -> content
    deny_policy: dict[str, Any] | None = None
    boundary_policy: dict[str, Any] = field(default_factory=boundary_policy_document)
    vault_policy: dict[str, Any] | None = None
    policies_by_file: dict[str, list[dict[str, Any]]] = field(default_factory=dict)


HEADER = (
    "# Generated by Agent Radius. Review before use.\n"
    "# Agent Radius never runs terraform plan or apply and never calls a mutating AWS API.\n\n"
)


def _versions_tf() -> str:
    return HEADER + (
        "terraform {\n"
        '  required_version = ">= 1.5.0"\n'
        "  required_providers {\n"
        "    aws = {\n"
        '      source  = "hashicorp/aws"\n'
        '      version = ">= 5.0"\n'
        "    }\n"
        "  }\n"
        "}\n"
    )


def _variables_tf(include_backup: bool) -> str:
    blocks = [
        ("agent_role_name", "string", '"ai-coding-agent"', "Name of the dedicated role your coding agent should use."),
        (
            "agent_trusted_principal_arns",
            "list(string)",
            "[]",
            "Principals allowed to assume the agent role. Empty means the account root (then narrow it).",
        ),
        (
            "agent_managed_policy_arns",
            "list(string)",
            '["arn:aws:iam::aws:policy/ReadOnlyAccess"]',
            "Policies the agent role gets. The boundary caps whatever you attach here.",
        ),
    ]
    if include_backup:
        blocks += [
            ("backup_region", "string", '"us-east-1"', "Region of the isolated backup vault."),
            ("isolated_vault_name", "string", '"agent-radius-isolated"', "Vault name in the separate backup account."),
            ("source_vault_name", "string", '"agent-radius-source"', "Vault in this account that receives the primary backups."),
            ("min_retention_days", "number", "7", "Vault lock minimum retention."),
            ("max_retention_days", "number", "365", "Vault lock maximum retention."),
            ("copy_retention_days", "number", "35", "How long cross-account copies are kept (must be within the lock window)."),
            ("backup_service_role_arn", "string", None, "IAM role AWS Backup uses to read the protected resources."),
        ]
    out = [HEADER.rstrip("\n") + "\n"]
    for name, typ, default, desc in blocks:
        body = f'variable "{name}" {{\n  description = {hcl_string(desc)}\n  type        = {typ}\n'
        if default is not None:
            body += f"  default     = {default}\n"
        body += "}\n"
        out.append(body)
    return "\n".join(out)


def _agent_role_tf(boundary: dict[str, Any]) -> str:
    return HEADER + (
        'data "aws_caller_identity" "current" {}\n\n'
        "locals {\n"
        "  agent_trusted_principals = length(var.agent_trusted_principal_arns) > 0 ? var.agent_trusted_principal_arns : [\n"
        '    "arn:aws:iam::${data.aws_caller_identity.current.account_id}:root",\n'
        "  ]\n"
        "}\n\n"
        "# Permissions boundary: the agent role can never exceed it, whatever\n"
        "# policies are attached later. It forbids every catalogued irreversible\n"
        "# action and any change to the boundary itself.\n"
        'resource "aws_iam_policy" "agent_boundary" {\n'
        '  name        = "agent-radius-agent-boundary"\n'
        '  description = "Ceiling for AI coding agents: no irreversible actions."\n'
        f"  policy      = jsonencode({render_value(boundary, 1)})\n"
        "}\n\n"
        'data "aws_iam_policy_document" "agent_trust" {\n'
        "  statement {\n"
        '    effect  = "Allow"\n'
        '    actions = ["sts:AssumeRole"]\n'
        "    principals {\n"
        '      type        = "AWS"\n'
        "      identifiers = local.agent_trusted_principals\n"
        "    }\n"
        "  }\n"
        "}\n\n"
        "# A role only the agent uses, narrower than any human's.\n"
        'resource "aws_iam_role" "agent" {\n'
        "  name                 = var.agent_role_name\n"
        "  assume_role_policy   = data.aws_iam_policy_document.agent_trust.json\n"
        "  permissions_boundary = aws_iam_policy.agent_boundary.arn\n"
        "  max_session_duration = 3600\n"
        "  tags = {\n"
        '    "managed-by" = "agent-radius"\n'
        '    "purpose"    = "ai-coding-agent"\n'
        "  }\n"
        "}\n\n"
        'resource "aws_iam_role_policy_attachment" "agent_managed" {\n'
        "  for_each   = toset(var.agent_managed_policy_arns)\n"
        "  role       = aws_iam_role.agent.name\n"
        "  policy_arn = each.value\n"
        "}\n"
    )


def _deny_tf(deny: dict[str, Any], principals: list[tuple[str, str]]) -> str:
    out = HEADER + (
        "# Explicit deny for every destructive action Agent Radius found the agent\n"
        "# credentials could perform. An explicit deny beats any allow.\n"
        'resource "aws_iam_policy" "agent_deny_destructive" {\n'
        '  name        = "agent-radius-deny-destructive"\n'
        '  description = "Denies the destructive actions found by Agent Radius."\n'
        f"  policy      = jsonencode({render_value(deny, 1)})\n"
        "}\n\n"
        'resource "aws_iam_role_policy_attachment" "agent_role_deny" {\n'
        "  role       = aws_iam_role.agent.name\n"
        "  policy_arn = aws_iam_policy.agent_deny_destructive.arn\n"
        "}\n"
    )
    used: set[str] = set()
    for kind, name in principals:
        tf = _tf_name(f"deny_{kind}_{name}")
        while tf in used:
            tf += "_x"
        used.add(tf)
        if kind == "role":
            out += (
                f"\n# Attach to the existing role the agent uses today.\n"
                f'resource "aws_iam_role_policy_attachment" "{tf}" {{\n'
                f"  role       = {hcl_string(name)}\n"
                "  policy_arn = aws_iam_policy.agent_deny_destructive.arn\n"
                "}\n"
            )
        else:
            out += (
                f"\n# Attach to the existing user whose keys the agent can read.\n"
                f'resource "aws_iam_user_policy_attachment" "{tf}" {{\n'
                f"  user       = {hcl_string(name)}\n"
                "  policy_arn = aws_iam_policy.agent_deny_destructive.arn\n"
                "}\n"
            )
    return out


def _vault_policy(account_id: str) -> dict[str, Any]:
    return {
        "Version": "2012-10-17",
        "Statement": [
            {
                "Sid": "AllowCopyFromSourceAccount",
                "Effect": "Allow",
                "Principal": {"AWS": f"arn:aws:iam::{account_id}:root"},
                "Action": "backup:CopyIntoBackupVault",
                "Resource": "*",
            }
        ],
    }


def _backup_tf(account_id: str, at_risk_arns: list[str], vault_policy: dict[str, Any]) -> str:
    resources = render_value(sorted(set(at_risk_arns)), 1)
    return HEADER + (
        "# Isolated, locked vault in a SEPARATE backup account. Credentials the\n"
        "# agent inherits in this account cannot delete copies stored there.\n"
        "# Configure this provider alias for the backup account before use.\n"
        'provider "aws" {\n'
        '  alias  = "backup_account"\n'
        "  region = var.backup_region\n"
        "  # assume_role {\n"
        '  #   role_arn = "arn:aws:iam::<BACKUP_ACCOUNT_ID>:role/<deployer>"\n'
        "  # }\n"
        "}\n\n"
        'resource "aws_backup_vault" "isolated" {\n'
        "  provider = aws.backup_account\n"
        "  name     = var.isolated_vault_name\n"
        "}\n\n"
        "# Compliance-mode lock: after changeable_for_days it can never be removed,\n"
        "# not even by the backup account's root user.\n"
        'resource "aws_backup_vault_lock_configuration" "isolated" {\n'
        "  provider            = aws.backup_account\n"
        "  backup_vault_name   = aws_backup_vault.isolated.name\n"
        "  changeable_for_days = 3\n"
        "  min_retention_days  = var.min_retention_days\n"
        "  max_retention_days  = var.max_retention_days\n"
        "}\n\n"
        'resource "aws_backup_vault_policy" "isolated" {\n'
        "  provider          = aws.backup_account\n"
        "  backup_vault_name = aws_backup_vault.isolated.name\n"
        f"  policy            = jsonencode({render_value(vault_policy, 1)})\n"
        "}\n\n"
        "# Source-account vault and plan that copy every at-risk resource across.\n"
        'resource "aws_backup_vault" "source" {\n'
        "  name = var.source_vault_name\n"
        "}\n\n"
        'resource "aws_backup_plan" "cross_account" {\n'
        '  name = "agent-radius-cross-account-copy"\n'
        "  rule {\n"
        '    rule_name         = "daily-with-cross-account-copy"\n'
        "    target_vault_name = aws_backup_vault.source.name\n"
        '    schedule          = "cron(0 3 * * ? *)"\n'
        "    lifecycle {\n"
        "      delete_after = 35\n"
        "    }\n"
        "    copy_action {\n"
        "      destination_vault_arn = aws_backup_vault.isolated.arn\n"
        "      lifecycle {\n"
        "        delete_after = var.copy_retention_days\n"
        "      }\n"
        "    }\n"
        "  }\n"
        "}\n\n"
        f"# Resources Agent Radius found AT_RISK or PARTIAL in account {account_id}.\n"
        'resource "aws_backup_selection" "at_risk" {\n'
        '  name         = "agent-radius-at-risk"\n'
        "  plan_id      = aws_backup_plan.cross_account.id\n"
        "  iam_role_arn = var.backup_service_role_arn\n"
        f"  resources    = {resources}\n"
        "}\n"
    )


def _state_tf(buckets: list[str]) -> str:
    out = HEADER + (
        "# Terraform state buckets: keep every version and lock it, so an agent\n"
        "# that deletes or overwrites state cannot make the loss permanent.\n"
        "# Object Lock on an existing bucket requires versioning; check your\n"
        "# provider version supports enabling it in place before applying.\n"
    )
    for bucket in sorted(set(buckets)):
        tf = _tf_name(f"state_{bucket}")
        out += (
            f'\nresource "aws_s3_bucket_versioning" "{tf}" {{\n'
            f"  bucket = {hcl_string(bucket)}\n"
            "  versioning_configuration {\n"
            '    status = "Enabled"\n'
            "  }\n"
            "}\n\n"
            f'resource "aws_s3_bucket_object_lock_configuration" "{tf}" {{\n'
            f"  bucket = {hcl_string(bucket)}\n"
            "  rule {\n"
            "    default_retention {\n"
            '      mode = "GOVERNANCE"\n'
            "      days = 30\n"
            "    }\n"
            "  }\n"
            f"  depends_on = [aws_s3_bucket_versioning.{tf}]\n"
            "}\n"
        )
    return out


def _readme(account_id: str, files: list[str], deny_actions: list[str], principals: list[tuple[str, str]],
            at_risk: list[str], state_buckets: list[str]) -> str:
    lines = [
        "# Agent Radius guardrails",
        "",
        f"Generated for account {account_id}. Agent Radius wrote these files and stopped there: it never runs",
        "`terraform plan` or `terraform apply`, and it never calls a mutating AWS API. Review every file before you use it.",
        "",
        "## Files",
        "",
    ]
    descriptions = {
        "versions.tf": "Provider requirements.",
        "variables.tf": "Inputs with safe defaults. `backup_service_role_arn` has no default on purpose.",
        "agent_role.tf": "A dedicated agent role with a permissions boundary that forbids every catalogued irreversible action.",
        "deny_destructive.tf": "An explicit deny for the destructive actions found in this scan, attached to the new agent role and to the principals the agent uses today.",
        "backup_vault.tf": "A compliance-locked vault in a separate backup account plus a plan that copies the at-risk resources there.",
        "state_bucket.tf": "Versioning and Object Lock for the Terraform state bucket(s).",
        "deny_policy.json": "The deny policy as plain JSON, for review or for use outside Terraform.",
    }
    for f in files:
        if f in descriptions:
            lines.append(f"- `{f}`: {descriptions[f]}")
    lines += ["", "## What the deny policy covers", ""]
    if deny_actions:
        lines.append(f"{len(deny_actions)} actions, attached to:")
        lines += [f"- {kind} `{name}`" for kind, name in principals] or ["- (no existing principal)"]
        lines += ["", "Actions:", ""] + [f"- `{a}`" for a in deny_actions]
    else:
        lines.append("No destructive permission was found, so no deny policy was generated.")
    if at_risk:
        lines += ["", "## Resources added to the cross-account backup plan", ""] + [f"- `{a}`" for a in sorted(set(at_risk))]
    if state_buckets:
        lines += ["", "## State buckets", ""] + [f"- `{b}`" for b in sorted(set(state_buckets))]
    lines += [
        "",
        "## Before you apply",
        "",
        "1. Run `terraform init` and `terraform validate` in this directory.",
        "2. Read the deny list: if your agent legitimately needs one of these actions in a dev account, scope it there, not here.",
        "   The boundary also blocks `dynamodb:BatchWriteItem` and `dynamodb:DeleteItem`, which ordinary application writes use;",
        "   if the agent needs data-plane writes, allow them on dev tables only.",
        "3. Point the agent at the new role and remove its access to the old keys or profiles.",
        "4. For `backup_vault.tf`, set up the `backup_account` provider first; the compliance lock becomes permanent after 3 days.",
        "",
    ]
    return "\n".join(lines)


def render_bundle(
    account_id: str,
    deny_actions: list[str],
    principals: list[tuple[str, str]],
    at_risk_arns: list[str],
    state_buckets: list[str],
) -> GuardrailBundle:
    bundle = GuardrailBundle()
    include_backup = bool(at_risk_arns)
    bundle.files["versions.tf"] = _versions_tf()
    bundle.files["variables.tf"] = _variables_tf(include_backup)
    bundle.files["agent_role.tf"] = _agent_role_tf(bundle.boundary_policy)
    bundle.policies_by_file["agent_role.tf"] = [bundle.boundary_policy]
    if deny_actions:
        bundle.deny_policy = deny_policy_document(deny_actions)
        bundle.files["deny_destructive.tf"] = _deny_tf(bundle.deny_policy, principals)
        bundle.files["deny_policy.json"] = json.dumps(bundle.deny_policy, indent=2) + "\n"
        bundle.policies_by_file["deny_destructive.tf"] = [bundle.deny_policy]
    if include_backup:
        bundle.vault_policy = _vault_policy(account_id)
        bundle.files["backup_vault.tf"] = _backup_tf(account_id, at_risk_arns, bundle.vault_policy)
        bundle.policies_by_file["backup_vault.tf"] = [bundle.vault_policy]
    if state_buckets:
        bundle.files["state_bucket.tf"] = _state_tf(state_buckets)
        bundle.policies_by_file["state_bucket.tf"] = []
    names = list(bundle.files) + ["README.md"]
    bundle.files["README.md"] = _readme(account_id, names, sorted(set(deny_actions)), principals, at_risk_arns, state_buckets)
    return bundle
